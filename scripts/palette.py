"""Rebuild light semantic tokens from the source palette, preserving alpha."""
import re
from pathlib import Path
root = Path(__file__).resolve().parent.parent
lines = (root / 'docs/product/colors(1).txt').read_text().splitlines()
tokens = {}
for i, line in enumerate(lines):
    if '/' not in line or not re.fullmatch(r'[A-Za-z0-9 /-]+', line):
        continue
    for candidate in lines[i+1:i+5]:
        match = re.search(r'\[(#[0-9A-Fa-f]{6}) (\d+)%\]', candidate)
        if match:
            name = re.sub(r'[^a-z0-9]+', '-', line.lower()).strip('-')
            value, alpha = match.groups()
            tokens[name] = value if alpha == '100' else value + f'{round(int(alpha)*255/100):02x}'
            break
(root / 'myteam/static/myteam/tokens.css').write_text('/* Generated by scripts/palette.py; light values. */\n:root {\n' + ''.join(f'  --{k}: {v};\n' for k, v in tokens.items()) + '}\n')
