"""Hidden-location conversation game; roles stay on each player's own device."""
from .four_person import FourPersonActivity

GAME_URL='https://spyfall.adrianocola.com/'


class Spyfall(FourPersonActivity):
    key='spyfall'
    version=1
    title='Spyfall'
    achievement_key='first_spyfall'
    game_url=GAME_URL

    def organizer_instructions(self):
        return ('Ты организуешь эту встречу: предложи время, создай звонок и комнату Spyfall, отправь обе ссылки группе. '
            'Перед стартом помоги всем разобраться в правилах и убедись, что каждый видит свою роль. '
            'Начните с одного шпиона и помогайте друг другу включаться в разговор, чтобы вопросы и обсуждение '
            'не оставались только между самыми активными.\n\n')

    def instructions(self,same_city):
        return ('Попробуйте вычислить шпиона среди коллег! В Spyfall почти все знают общую секретную локацию, '
            'а один участник — шпион — пытается её угадать. Задавайте друг другу вопросы: достаточно точные, '
            'чтобы распознать шпиона, и достаточно осторожные, чтобы не выдать место.\n\n'
            'Договоритесь в Telegram об удобном времени и созвонитесь. Организатор создаст комнату на '
            'spyfall.adrianocola.com и пришлёт ссылку. Каждый откроет свою роль на собственном устройстве — '
            'показывать её остальным не нужно. Заложите 30–45 минут на несколько коротких раундов.\n\n'
            'Давайте каждому побыть в центре внимания: чередуйте собеседников, слушайте ответы и оставляйте место '
            'для разных версий. Подозрения — часть игры; обсуждайте игровые ответы дружелюбно. После раскрытия ролей '
            'можно поделиться, какая реплика вас запутала или навела на разгадку.\n\n'
            'После игры поделитесь результатом активности в МАЙТИМ.')
